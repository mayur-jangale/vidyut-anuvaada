from pathlib import Path as _Path

_TSV = _Path(__file__).resolve().parent.parent.parent / "stardict_data" / "spokensanskrit_clean.tsv"
if _TSV.exists():
	_tsv_text = _TSV.read_text(encoding="utf-8")
	_tsv_added = 0
	for _line in _tsv_text.splitlines():
		if not _line or "\t" not in _line:
			continue
		_w, _r = _line.split("\t", 1)
		if not _w or not _re.search(r"[\u0900-\u097F]", _w):
			continue
		if _w in _BUILTIN:
			continue
		_meaning = _r.strip()
		if not _meaning:
			continue
		_pos = "noun"
		_m = _re.match(r"^(m|f|n|verb|adj|adv|particle|pron|pref|suf|ind):\s*(.+)", _meaning)
		if _m:
			_pos_map = {"m": "noun-m", "f": "noun-f", "n": "noun-n", "verb": "verb", "adj": "adj", "adv": "adv", "particle": "particle", "pron": "pron", "pref": "prefix", "suf": "suffix", "ind": "indecl"}
			_pos = _pos_map.get(_m.group(1), "noun")
			_meaning = _m.group(2).strip()
		if len(_meaning) > 60:
			_meaning = _meaning[:57] + "..."
		_meaning = _meaning.replace("'", "\'")
		_BUILTIN[_w] = (_w, _pos, _meaning)
		_tsv_added += 1
	print(f"[dictionary] Loaded spokensanskrit: {_tsv_added} entries")
