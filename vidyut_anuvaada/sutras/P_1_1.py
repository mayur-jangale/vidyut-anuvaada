# ============================================================
# P_1_1_4 lRdAtuH
# ============================================================
def apply_1_1_4(word, pos="", SUTRA_TOKEN=""):
	"""lRdAtuH - roots ending in ic sounds (इ, उ, ऋ, ऌ and long forms)."""
	root = word.strip()
	if not root:
		return word
	# Check last non-combining character
	last = ''
	for c in reversed(root):
		if c in AYOGAVAHA or c in COMBINING_SET:
			continue
		last = c
		break
	ic_vowels = IK_ALL
	if last in ic_vowels:
		return f"lrdatu:{word}"
	return word

