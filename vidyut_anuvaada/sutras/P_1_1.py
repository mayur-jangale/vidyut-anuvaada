# P_1_1_1 vRddhirAdaic
# ============================================================
def apply_1_1_1(word, pos="", SUTRA_TOKEN=""):
	"""vRddhi = {A, ai, au}. Returns the vrddhi set with any matches found."""
	matched = sorted(c for c in VRDDHI if c in word)
	return f"vṛddhi={{{','.join(sorted(VRDDHI))}}};input={word};matches={''.join(matched)}"

